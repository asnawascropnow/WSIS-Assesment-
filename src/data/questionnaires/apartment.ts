type ApartmentInputType = 'text' | 'textarea' | 'number' | 'email' | 'url' | 'tel' | 'table' | 'file'

const question = (id: string, label: string, example = '', inputType: ApartmentInputType = 'textarea') => ({
  id,
  question: label,
  example,
  inputType,
})

const table = (id: string, label: string, columns: string[], rows: string[], example: string) => ({
  id,
  question: label,
  example,
  inputType: 'table' as const,
  tableDefinition: {
    id,
    columns,
    rows: rows.map((row, index) => ({ id: `${id}_row_${index + 1}`, label: row })),
  },
})

